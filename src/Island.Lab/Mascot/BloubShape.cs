using System.Numerics;
using static Island.Lab.Mascot.BloubMath;

namespace Island.Lab.Mascot;

/// <summary>A 2D point in double precision (engine-internal; the frame exposes floats).</summary>
public readonly record struct PointD(double X, double Y);

/// <summary>
/// A silhouette = a radial profile r(theta) plus a pose.
///
/// Every shape is sampled at the SAME angles, so any two shapes have points that
/// correspond one to one and morphing reduces to a linear interpolation of radii.
/// That is what makes transitions clean without a path-morphing library.
/// </summary>
public sealed record Silhouette
{
    public required double[] Radii { get; init; }
    /// <summary>Profile rotation, radians.</summary>
    public double Rot { get; init; }
    /// <summary>Centre offset, in ball-radius units.</summary>
    public double Cx { get; init; }
    public double Cy { get; init; }
    /// <summary>Squash and stretch, applied in screen space (after rotation).</summary>
    public double Sx { get; init; } = 1;
    public double Sy { get; init; } = 1;
}

/// <summary>Radial profiles measured off the reference video (profiles.ts).</summary>
public enum ProfileName { Egg, Hexagon, Triangle }

/// <summary>Silhouette helpers (shape.ts).</summary>
public static class BloubShape
